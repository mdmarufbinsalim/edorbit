/**
 * Content data for the printing press concept. Pure data, no UI.
 *
 * First-press years follow the place-and-date indexes of the ISTC and the
 * tables in Febvre and Martin. Many early dates come from the first dated or
 * datable surviving book, so a press may have started a little earlier:
 * those are flagged `approximate`. Reviewers: check each row against the ISTC
 * before changing it.
 */

/** Language most people spoke in the town around 1500, for the language filter. */
export type Language =
  | "German"
  | "Italian"
  | "French"
  | "Dutch"
  | "English"
  | "Spanish"
  | "Catalan"
  | "Portuguese"
  | "Czech"
  | "Polish"
  | "Hungarian"
  | "Danish"
  | "Swedish"
  | "Serbian";

export interface PressTown extends HistoricalYear {
  id: string;
  name: string;
  lonLat: LonLat;
  /** Today's name or country, when that helps. */
  modern?: string;
  /** First printer, only where the sources agree. */
  printer?: string;
  language: Language;
  /** Had a university before its first press. */
  university: boolean;
  /** On a major navigable river. */
  river?: string;
  note?: string;
  sourceIds: readonly string[];
}

